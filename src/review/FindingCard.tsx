import { useState, type ReactNode } from 'react';
import { Check, ChevronDown, ChevronUp, FlaskConical, Globe, Info, Pencil, Send, Upload, X } from 'lucide-react';
import { fmtDate } from '../domain/dates';
import type { Finding } from '../domain/engine';
import { TYPE_LABEL } from '../domain/rules';
import { SOURCES } from '../domain/sources';
import { useLang } from '../i18n';
import type { DoctorAction, LabRequest } from '../store';
import { Button, Chip, IconButton, SeverityChip, SeverityIcon } from '../ui/ui';
import { reasonLabel } from './DismissDialog';

const ACTION_LABEL = {
  es: { accepted: 'Aceptado', modified: 'Modificado', dismissed: 'Descartado' },
  en: { accepted: 'Accepted', modified: 'Modified', dismissed: 'Dismissed' },
};

export function FindingCard({
  f, action, lab, onAct, onDismiss, onSource, onLab,
}: {
  f: Finding;
  action?: DoctorAction;
  lab?: LabRequest;
  onAct: (a: DoctorAction | null) => void;
  onDismiss: () => void;
  onSource: () => void;
  onLab: (status: LabRequest['status']) => void;
}) {
  const { lang, t } = useLang();
  const [showFacts, setShowFacts] = useState(false);
  const [editing, setEditing] = useState(false);
  const [note, setNote] = useState('');
  const types = f.kind === 'missing_data' ? ['missing_data' as const] : [...new Set(f.reasons.map((r) => r.type))];
  const sources = [...new Set(f.reasons.map((r) => r.sourceId))].map((id) => SOURCES[id]);
  const now = () => new Date().toISOString();

  return (
    <article
      className={`rounded-lg border p-4 transition-colors ${action ? 'border-line bg-canvas' : 'border-line bg-white'} ${
        f.severity === 'major' && !action ? 'border-l-4 border-l-major' : ''
      }`}
      aria-label={`${f.title}: ${f.message}`}
      data-tour="finding"
    >
      <div className="flex gap-3">
        <SeverityIcon severity={f.severity} className="mt-0.5 size-5 shrink-0" />
        <div className="min-w-0 flex-1">
          <div className="flex items-start gap-2">
            <div className="min-w-0 flex-1">
              <h3 className="text-[15px] font-medium text-ink">{f.title}</h3>
              {f.meds.length > 0 && <div className="text-sm text-ink-2">{f.meds.join(', ')}</div>}
            </div>
            {f.kind === 'rule' && (
              <Button size="sm" variant="link" onClick={onSource} data-tour="finding-source">
                {t('Fuente', 'Source')}
              </Button>
            )}
            <IconButton
              label={showFacts ? t('Ocultar datos usados', 'Hide data used') : t('Ver datos usados', 'Show data used')}
              className="size-8"
              onClick={() => setShowFacts((v) => !v)}
              aria-expanded={showFacts}
              data-tour="finding-info"
            >
              <Info className="size-4" />
            </IconButton>
          </div>

          <div className="mt-2 flex flex-wrap gap-1.5">
            <SeverityChip severity={f.severity} />
            {types.map((ty) => (
              <Chip key={ty}>{TYPE_LABEL[lang][ty]}</Chip>
            ))}
            {f.actionToday && <Chip tone="solidMajor">{t('Actuar hoy', 'Act today')}</Chip>}
            {f.needsJudgement && <Chip tone="judge">{t('Requiere juicio clínico', 'Needs clinical judgement')}</Chip>}
          </div>

          <p className="mt-2 text-sm font-medium text-ink">{f.message}</p>
          {f.reasons.length > 1 && (
            <ul className="mt-1.5 space-y-1 text-[13px] text-ink-2">
              {f.reasons.slice(1).map((r) => (
                <li key={r.ruleId} className="flex gap-2">
                  <span className="w-7 shrink-0 font-medium text-ink-3">{r.ruleId}</span>
                  <span>{r.message}</span>
                </li>
              ))}
            </ul>
          )}
          {f.needsJudgement && <p className="mt-2 rounded-md bg-judge-bg px-3 py-2 text-[13px] text-judge">{f.needsJudgement}</p>}
          <p className="mt-2 text-[13px] text-ink-2">
            <span className="font-medium text-ink">{t('Acción sugerida', 'Suggested action')}: </span>
            {f.action}
          </p>

          <div className="mt-2 space-y-0.5 text-xs text-ink-3">
            {f.kind === 'rule' ? (
              <>
                <div>{f.reasons.map((r) => `${t('Regla', 'Rule')} ${r.ruleId} v${r.ruleVersion}`).join(' · ')}</div>
                {sources.map((s) => (
                  <div key={s.id} className="flex items-center gap-1">
                    <Globe aria-hidden className="size-3.5" />
                    {s.document[lang]} · {s.section[lang]}
                  </div>
                ))}
              </>
            ) : (
              <div>
                {t(
                  `Generado por la puerta de datos a partir de los requisitos de ${f.missing!.blockedRules.join(', ')}`,
                  `Generated by the data gate from the requirements of ${f.missing!.blockedRules.join(', ')}`,
                )}
              </div>
            )}
          </div>

          {showFacts && (
            <div className="mt-3 rounded-md border border-line bg-white">
              <div className="border-b border-line px-3 py-2 text-xs font-medium text-ink-2">{t('Datos usados por las reglas', 'Data used by the rules')}</div>
              <ul className="divide-y divide-line text-[13px]">
                {f.kind === 'missing_data' ? (
                  <li className="px-3 py-2">
                    {f.missing!.status.value
                      ? `${f.missing!.status.value} · ${fmtDate(f.missing!.status.date)}`
                      : t('Sin valor registrado', 'No value on record')}{' '}
                    · {t('ventana máxima', 'maximum window')} {f.missing!.status.maxDays} {t('días', 'days')}
                  </li>
                ) : (
                  uniqueFacts(f).map((x) => (
                    <li key={x.key} className="px-3 py-2">
                      <div className="flex justify-between gap-3">
                        <span className="font-medium">{x.label}</span>
                        <span>{x.value}</span>
                      </div>
                      <div className="text-xs text-ink-3">
                        {x.origin}
                        {x.date && ` · ${fmtDate(x.date)}`}
                      </div>
                      {x.evidence && (
                        <q className="mt-0.5 block text-xs text-ink-2 italic" lang={lang}>
                          {x.evidence}
                        </q>
                      )}
                    </li>
                  ))
                )}
              </ul>
            </div>
          )}

          {f.kind === 'missing_data' && f.missing!.tests.length > 0 && (
            <div className="mt-3 rounded-md border border-dashed border-line-strong p-3 text-[13px]" data-tour="finding-missing">
              {!lab && (
                <div className="flex flex-wrap gap-2">
                  <Button size="sm" variant="link" icon={<FlaskConical className="size-4" />} onClick={() => onLab('draft')}>
                    {t('Borrador de analítica', 'Draft lab order')}
                  </Button>
                  <Button size="sm" icon={<Upload className="size-4" />} onClick={() => onLab('upload_requested')}>
                    {t('Pedir resultados al paciente', 'Ask patient for results')}
                  </Button>
                </div>
              )}
              {lab?.status === 'draft' && (
                <div className="flex flex-wrap items-center gap-2">
                  <span className="text-ink-2">
                    {t('Borrador', 'Draft')}: {lab.tests.join(', ')} · {t('pendiente de su envío', 'waiting for you to send')}
                  </span>
                  <Button size="sm" variant="primary" icon={<Send className="size-4" />} onClick={() => onLab('sent')}>
                    {t('Enviar solicitud', 'Send order')}
                  </Button>
                </div>
              )}
              {lab?.status === 'sent' && (
                <span className="text-brand-800">
                  {t('Solicitud enviada', 'Order sent')}: {lab.tests.join(', ')}
                </span>
              )}
              {lab?.status === 'upload_requested' && (
                <span className="text-brand-800">
                  {t('Mensaje enviado al paciente para subir resultados en Doctoralia', 'Message sent asking the patient to upload results in Doctoralia')}
                </span>
              )}
            </div>
          )}

          {action ? (
            <div className="mt-3 flex flex-wrap items-center gap-2 text-[13px] text-ink-2">
              <Check aria-hidden className="size-4 text-brand-700" />
              <span className="font-medium text-ink">{ACTION_LABEL[lang][action.kind]}</span>
              {action.reason && <span>· {reasonLabel(action.reason, lang)}</span>}
              {action.note && <span>· {action.note}</span>}
              <button type="button" className="cursor-pointer text-brand-800 underline" onClick={() => onAct(null)}>
                {t('Deshacer', 'Undo')}
              </button>
            </div>
          ) : editing ? (
            <div className="mt-3 space-y-2">
              <label className="block text-xs text-ink-2" htmlFor={`note-${f.key}`}>
                {t('¿Qué ha cambiado respecto a la acción sugerida?', 'What did you change from the suggested action?')}
              </label>
              <textarea
                id={`note-${f.key}`}
                value={note}
                onChange={(e) => setNote(e.target.value)}
                rows={2}
                className="w-full rounded-md border border-line-strong p-2 text-sm outline-none focus:border-brand-600"
              />
              <div className="flex gap-2">
                <Button
                  size="sm"
                  variant="primary"
                  disabled={!note.trim()}
                  onClick={() => onAct({ kind: 'modified', note: note.trim(), hash: f.hash, at: now() })}
                >
                  {t('Guardar', 'Save')}
                </Button>
                <Button size="sm" variant="ghost" onClick={() => setEditing(false)}>
                  {t('Cancelar', 'Cancel')}
                </Button>
              </div>
            </div>
          ) : (
            <div className="mt-3 flex flex-wrap gap-2" data-tour="finding-actions">
              <Button size="sm" variant="link" icon={<Check className="size-4" />} onClick={() => onAct({ kind: 'accepted', hash: f.hash, at: now() })}>
                {t('Aceptar', 'Accept')}
              </Button>
              <Button size="sm" icon={<Pencil className="size-4" />} onClick={() => setEditing(true)}>
                {t('Modificar', 'Modify')}
              </Button>
              <Button size="sm" variant="ghost" icon={<X className="size-4" />} onClick={onDismiss}>
                {t('Descartar', 'Dismiss')}
              </Button>
            </div>
          )}
        </div>
      </div>
    </article>
  );
}

function uniqueFacts(f: Finding) {
  const seen = new Set<string>();
  return f.reasons.flatMap((r) => r.facts).filter((x) => {
    if (seen.has(x.key)) return false;
    seen.add(x.key);
    return true;
  });
}

export function Collapsible({ title, children }: { title: string; children: ReactNode }) {
  const [open, setOpen] = useState(false);
  return (
    <div>
      <button
        type="button"
        onClick={() => setOpen((v) => !v)}
        aria-expanded={open}
        className="flex h-10 w-full cursor-pointer items-center gap-2 text-sm font-medium text-ink-2 hover:text-ink"
      >
        {open ? <ChevronUp className="size-4" /> : <ChevronDown className="size-4" />}
        {title}
      </button>
      {open && <div className="space-y-3">{children}</div>}
    </div>
  );
}
